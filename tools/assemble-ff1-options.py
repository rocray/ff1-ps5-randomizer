#!/usr/bin/env python3
"""Regenerate checked-in patch header: pip install py65, then run this script.
Two passes, explicit address limits; no ROM or proprietary bytes are inputs.
"""
from pathlib import Path
import re,json
from py65.assembler import Assembler
from py65.devices.mpu6502 import MPU
root=Path(__file__).resolve().parents[1]
lines=[l.split(';')[0].strip() for l in (root/'tools/asm/ff1-options.asm').read_text().splitlines()]
labels={};blocks=[];a=Assembler(MPU())
for phase in range(2):
 pc=0;group='';blocks=[];block=None;limit=0x10000
 for line in lines:
  if not line:continue
  if line.startswith('.group'):group=line.split()[1];continue
  if line.startswith('.org'):
   if block is not None:assert pc<=limit,(hex(pc),hex(limit))
   pc=int(line.split('$')[1],16);block={'group':group,'at':pc,'data':[]};blocks.append(block);limit=0x10000;continue
  if line.startswith('.limit'):limit=int(line.split('$')[1],16);continue
  if line.endswith(':'):labels[line[:-1]]=pc;continue
  if line.startswith('.word'):
   data=[]
   for name in line[5:].split(','):
    v=labels.get(name.strip(),0);data.extend([v&255,v>>8])
  else:
   op,*args=line.split(maxsplit=1);arg=args[0] if args else ''
   if re.fullmatch('[a-z_]+',arg):arg=f'${labels.get(arg,pc):04x}'
   data=a.assemble(op+' '+arg,pc=pc)
  block['data']+=data;pc+=len(data)
 assert pc<=limit
out=['// Generated by tools/assemble-ff1-options.py; edit tools/asm/ff1-options.asm.', '#pragma once','#include <cstdint>','namespace ff1logic {','struct Patch {unsigned offset, size; const std::uint8_t *data;};']
for i,b in enumerate(blocks):out.append('inline constexpr std::uint8_t patch_%u[]={%s};'%(i,','.join(hex(v) for v in b['data'])))
for group in ['major','shops']:
 out.append('inline constexpr Patch '+group+'_patches[]={')
 for i,b in enumerate(blocks):
  if b['group']==group:out.append('{0x%x,sizeof(patch_%u),patch_%u},'%(0x30010+b['at'],i,i))
 out.append('};')
for name,address in labels.items():out.append('inline constexpr unsigned '+name+'=0x%x;'%address)
out.append('}')
(root/'src/ff1logic/patches.hpp').write_text('\n'.join(out)+'\n')
print('Generated',len(blocks),'bounded patches:',sum(len(b['data']) for b in blocks),'bytes')
print(json.dumps(labels))
